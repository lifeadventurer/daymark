import type { GridPoint } from "../engine/types";
import type {
  PentominoTilingPlacement,
  PentominoTilingPieceId,
} from "./pentominoTilings";

export interface PentominoBuildGalleryItem {
  id: string;
  targetPieceId: PentominoTilingPieceId;
  width: number;
  height: number;
  placements: PentominoTilingPlacement[];
}

function placement(
  pieceId: PentominoTilingPlacement["pieceId"],
  cells: Array<[number, number]>,
): PentominoTilingPlacement {
  return {
    pieceId,
    cells: cells.map(([x, y]): GridPoint => ({ x, y })),
  };
}

